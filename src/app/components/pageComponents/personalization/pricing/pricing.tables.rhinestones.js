export function getRhinestonesUnitPrice(chargedSize, variant, quantityBracket) {
  const quantityIndex = RHINESTONES_QUANTITY_BRACKETS.indexOf(Number(quantityBracket));
  if (quantityIndex === -1) return null;

  const variantTable = RHINESTONES_PRICING_TABLE[String(variant)];
  if (!variantTable) return null;

  const sizePrices = variantTable[String(chargedSize)];
  if (!sizePrices) return null;

  return sizePrices[quantityIndex] ?? null;
}