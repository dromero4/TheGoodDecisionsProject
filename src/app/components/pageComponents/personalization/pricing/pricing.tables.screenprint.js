export const SCREENPRINT_SUPPORTED_CHARGED_SIZES = ["a4", "a3"];
export const SCREENPRINT_SUPPORTED_INK_COUNTS = ["1", "2", "3", "4"];

export function getScreenprintUnitPrice(chargedSize, inkCount, quantityBracket) {
  const sizeTable = SCREENPRINT_PRICING_TABLE[chargedSize];
  if (!sizeTable) return null;

  const inkTable = sizeTable[String(inkCount)];
  if (!inkTable) return null;

  return inkTable[quantityBracket] ?? null;
}