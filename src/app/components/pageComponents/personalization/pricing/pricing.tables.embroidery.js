export const EMBROIDERY_SUPPORTED_CHARGED_SIZES = Object.keys(
  EMBROIDERY_PRICING_TABLE
);

export function getEmbroideryUnitPrice(chargedSize, quantityBracket) {
  const sizeTable = EMBROIDERY_PRICING_TABLE[chargedSize];
  if (!sizeTable) return null;

  return sizeTable[quantityBracket] ?? null;
}

/**
 * Variantes que usan esta tabla.
 */
export const EMBROIDERY_NORMAL_VARIANTS = [
  "matizado",
  "mixto",
  "salto_puntada",
];

export function isEmbroideryNormalVariant(variant) {
  return EMBROIDERY_NORMAL_VARIANTS.includes(variant);
}