export function getVinylUnitPrice(chargedSize, variant, quantityBracket) {
  const quantityIndex = VINYL_QUANTITY_BRACKETS.indexOf(Number(quantityBracket));
  if (quantityIndex === -1) return null;

  const variantTable = VINYL_PRICING_TABLE[String(variant)];
  if (!variantTable) return null;

  const sizePrices = variantTable[String(chargedSize)];
  if (!sizePrices) return null;

  return sizePrices[quantityIndex] ?? null;
}